CREATE TABLE TB_APPLICATION_PROPERTY (
    PROPERTY_NAME VARCHAR(100) NOT NULL COMMENT '프로퍼티 이름',
    PROPERTY_VALUE VARCHAR(1024) NOT NULL COMMENT '프로퍼티 값',
    CONSTRAINT TB_APPLICATION_PROPERTY_PK PRIMARY KEY (PROPERTY_NAME)
) COMMENT='애플리케이션 전역에서 사용되는 프로퍼티';

CREATE TABLE TB_APPLICATION_SEQUENCER (
    SEQUENCER_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '시퀀서 ID',
    NAME VARCHAR(100) NOT NULL COMMENT '시퀀서 이름',
    DISPLAY_NAME VARCHAR(255) COMMENT '출력시 보여줄 이름',
    VALUE INTEGER NOT NULL COMMENT '시퀀서 값',
    CONSTRAINT TB_APPLICATION_SEQUENCER_PK PRIMARY KEY (SEQUENCER_ID)
) COMMENT='애플리케이션 전역에서 사용되는 시퀀서';

CREATE UNIQUE INDEX TB_APPLICATION_SEQUENCER_UIDX1 ON TB_APPLICATION_SEQUENCER (NAME);
