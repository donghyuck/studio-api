CREATE TABLE IF NOT EXISTS TB_PLATFORM_TEAM (
    TEAM_ID BIGINT NOT NULL AUTO_INCREMENT,
    COMPANY_ID BIGINT NULL,
    NAME VARCHAR(255) NOT NULL,
    SLUG VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(1000) NULL,
    VISIBILITY VARCHAR(20) NOT NULL DEFAULT 'PRIVATE',
    JOIN_POLICY VARCHAR(20) NOT NULL DEFAULT 'INVITE_ONLY',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    RAG_ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
    RAG_REPLY_MODE VARCHAR(20) NOT NULL DEFAULT 'MENTION',
    PERMISSION_VERSION BIGINT NOT NULL DEFAULT 1,
    ARCHIVED_AT TIMESTAMP NULL,
    ARCHIVED_BY BIGINT NULL,
    CREATED_BY BIGINT NOT NULL,
    UPDATED_BY BIGINT NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (TEAM_ID),
    UNIQUE KEY UK_PLATFORM_TEAM_SLUG (SLUG),
    KEY IDX_PLATFORM_TEAM_COMPANY (COMPANY_ID),
    KEY IDX_PLATFORM_TEAM_DISCOVERY (VISIBILITY, STATUS),
    CONSTRAINT FK_PLATFORM_TEAM_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES TB_APPLICATION_COMPANY(COMPANY_ID)
);

CREATE TABLE IF NOT EXISTS TB_PLATFORM_TEAM_MEMBER (
    MEMBER_ID BIGINT NOT NULL AUTO_INCREMENT,
    TEAM_ID BIGINT NOT NULL,
    USER_ID BIGINT NOT NULL,
    ROLE VARCHAR(20) NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CREATED_BY BIGINT NOT NULL,
    UPDATED_BY BIGINT NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (MEMBER_ID),
    UNIQUE KEY UK_PLATFORM_TEAM_MEMBER (TEAM_ID, USER_ID),
    KEY IDX_PLATFORM_TEAM_MEMBER_USER (USER_ID, STATUS),
    CONSTRAINT FK_PLATFORM_TEAM_MEMBER_TEAM FOREIGN KEY (TEAM_ID) REFERENCES TB_PLATFORM_TEAM(TEAM_ID) ON DELETE CASCADE
);
